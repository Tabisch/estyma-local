#!/usr/bin/env python3
"""Generate the files that are built from the code's own definitions:

- docs/registers.md       from proxy/catalog.py (registers)
- docs/configuration.md   from proxy/config.py  (environment variables)
- .env.example            from proxy/config.py

Run it after changing either module:  python3 tools/gendocs.py
``--check`` only reports files that are out of date (exit code 1), which is
what tests/test_docs.py does.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "proxy"))

import catalog as C  # noqa: E402
import config as K  # noqa: E402

GENERATED = "<!-- Generated by tools/gendocs.py from proxy/{src}. Do not edit by hand. -->\n\n"

_ENCODING = {
    "x1": "x1", "d10": "÷10", "d100": "÷100", "u8": "8-bit", "u16": "16-bit", "s16": "signed 16-bit",
    "u8/10": "8-bit, ÷10", "u16/10": "16-bit, ÷10", "time": "Unix time", "hex": "bit mask", "alarm": "x1",
}


def _num(v, scaled: bool) -> str:
    return f"{v:.1f}" if scaled else str(v)


def _values(r: C.Reg) -> str:
    if r.note:
        return r.note
    if r.values:
        return ", ".join(f"{k} {en}" for k, (en, _de) in sorted(r.values.items()))
    if r.range:
        lo, hi = r.range
        unit = f" {r.unit}" if r.unit else ""
        if r.scale != 1:
            return (f"raw {round(lo * r.scale)}..{round(hi * r.scale)} = "
                    f"{_num(lo, True)}..{_num(hi, True)}{unit}")
        return f"{lo}..{hi}{unit}"
    return r.unit


def _function(r: C.Reg) -> str:
    text = r.doc or r.label
    return text + (f" *({r.conf})*" if r.conf in ("likely", "guess") else "")


def registers_md() -> str:
    out = [GENERATED.format(src="catalog.py"), """# Registers

All registers of the Estyma controller identified so far. The controller reports
them as `reg,idx,value` in `ZAPISZ_ODCZYT`; idx 1 is the value, idx 3 and 4 hold
the min and max of settings. Any register can be read by adding `reg,idx` to the
`ODCZYT` list in the reply to `/device/connect`; the controller reports it on its
next request.

Encoding:

- **x1**: the raw value as is.
- **÷10 / ÷100**: divide the raw value.
- **8-bit**: reported as `0x100 + value`, use the low byte.
- **16-bit**: use the low 16 bits (reads sometimes carry garbage in the upper bits).
- **signed 16-bit**: low 16 bits as a signed number.

Status: confirmed unless marked *(likely)* or *(guess)*. How each was found:
[register-mapping.md](register-mapping.md) (cloud comparison) and the cloud
service panel, whose rows name their register.

The ranges are the ones the cloud panels offer. The web UI and the settings
page use the same definitions (`proxy/catalog.py`).
"""]
    for key, title in C.SECTIONS.items():
        service = key in C.SERVICE_SECTIONS
        out.append(f"\n## {title}\n\n")
        if service:
            out.append("| Register | Function | Encoding | Range / values | Panel name (Polish) |\n"
                       "|---|---|---|---|---|\n")
        else:
            out.append("| Register | Function | Encoding | Range / values |\n|---|---|---|---|\n")
        for r in C.REGS:
            if r.section != key or r.reg in C.GROUPED:
                continue
            cells = [str(r.reg), _function(r), _ENCODING[r.decode], _values(r)]
            if service:
                cells.append(r.panel)
            out.append("| " + " | ".join(cells) + " |\n")
        for row in C.GROUP_ROWS.get(key, ()):
            out.append("| " + " | ".join(row) + " |\n")
        if key == "alarms":
            out.append("\nThe slot in use follows the counter. Timestamps run about 45 minutes "
                       "behind real time.\n")
    out.append("\nNot found yet: rated power, minimum blower speed, blower air speed "
               "F(30 %) / F(100 %).\n")
    return "".join(out)


def _default(e: K.Env) -> str:
    return f"`{e.default}`" if e.default else "(empty)"


def configuration_md() -> str:
    out = [GENERATED.format(src="config.py"), """# Configuration

Everything is set with environment variables: in Portainer under the stack's
*Environment variables*, with the docker compose CLI in `.env` (copy
[`.env.example`](../.env.example)). `docker-compose.yml` passes the variables
marked *compose* on to the container; the others keep their default unless
you add them to `docker-compose.yml` yourself.
"""]
    for key, (title, intro) in K.SECTIONS.items():
        out.append(f"\n## {title}\n\n{intro}\n\n| Variable | Default | Compose | Meaning |\n"
                   "|---|---|---|---|\n")
        for e in K.ENV:
            if e.section == key:
                out.append(f"| `{e.name}` | {_default(e)} | {'yes' if e.compose else ''} | {e.help} |\n")
    return "".join(out)


def env_example() -> str:
    out = ["# Generated by tools/gendocs.py from proxy/config.py. Do not edit by hand.\n"
           "# Copy to .env (never commit .env). See docs/configuration.md.\n"]
    for key, (title, _intro) in K.SECTIONS.items():
        rows = [e for e in K.ENV if e.section == key and e.example]
        if not rows:
            continue
        out.append(f"\n# {title}\n")
        for e in rows:
            out.append(f"# {e.help.replace('`', '').replace(chr(92), '')}\n"
                       f"{e.name}={'' if e.secret else e.default}\n")
    return "".join(out)


FILES = {
    "docs/registers.md": registers_md,
    "docs/configuration.md": configuration_md,
    ".env.example": env_example,
}


def stale() -> list[str]:
    bad = []
    for rel, build in FILES.items():
        try:
            with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
                if fh.read() == build():
                    continue
        except OSError:
            pass
        bad.append(rel)
    return bad


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--check" in argv:
        bad = stale()
        for rel in bad:
            print(f"{rel} is out of date, run: python3 tools/gendocs.py")
        return 1 if bad else 0
    for rel, build in FILES.items():
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as fh:
            fh.write(build())
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
